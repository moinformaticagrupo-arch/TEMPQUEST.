-- Esquema PostgreSQL para Supabase, adaptado del dump MySQL de sensores_db.
-- Ejecutar en Supabase SQL Editor. No contiene DROP ni borra datos existentes.
CREATE TABLE IF NOT EXISTS public.dispositivos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  ubicacion VARCHAR(100),
  tipo VARCHAR(50) DEFAULT 'sense HAT',
  activo BOOLEAN DEFAULT TRUE,
  fecha_registro TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS public.mediciones (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_dispositivo INTEGER NOT NULL REFERENCES public.dispositivos(id),
  humedad NUMERIC(5,2),
  presion NUMERIC(7,2),
  temperatura NUMERIC(5,2),
  fecha_hora TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS public.simulacion_estado (
  id SMALLINT PRIMARY KEY CHECK(id=1),
  activa BOOLEAN NOT NULL DEFAULT FALSE,
  escenario VARCHAR(32) NOT NULL DEFAULT 'ninguno',
  temperatura NUMERIC(5,2) NOT NULL DEFAULT 22,
  humedad NUMERIC(5,2) NOT NULL DEFAULT 48,
  cpu SMALLINT NOT NULL DEFAULT 38 CHECK(cpu BETWEEN 0 AND 100),
  temp_base NUMERIC(5,2) NOT NULL DEFAULT 22,
  hum_base NUMERIC(5,2) NOT NULL DEFAULT 48,
  cpu_base SMALLINT NOT NULL DEFAULT 38,
  nodo_offline BOOLEAN NOT NULL DEFAULT FALSE,
  actualizado TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  ultimo_tick TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
