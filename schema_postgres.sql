CREATE TABLE IF NOT EXISTS public.sensores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  temperatura NUMERIC(5,2) NOT NULL,
  humedad NUMERIC(5,2) NOT NULL,
  fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS public.simulacion_estado (
  id SMALLINT PRIMARY KEY CHECK(id=1),
  activa BOOLEAN NOT NULL DEFAULT FALSE,
  escenario VARCHAR(32) NOT NULL DEFAULT 'ninguno',
  temperatura NUMERIC(5,2) NOT NULL DEFAULT 22,
  humedad NUMERIC(5,2) NOT NULL DEFAULT 48,
  cpu SMALLINT NOT NULL DEFAULT 38 CHECK(cpu BETWEEN 0 AND 100),
  temp_base NUMERIC(5,2) NOT NULL DEFAULT 22,
  hum_base NUMERIC(5,2) NOT NULL DEFAULT 48,
  cpu_base SMALLINT NOT NULL DEFAULT 38,
  nodo_offline BOOLEAN NOT NULL DEFAULT FALSE,
  actualizado TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  ultimo_tick TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
